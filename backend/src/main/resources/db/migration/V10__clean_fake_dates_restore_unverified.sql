-- 1. 将在 2026-09-27 批量灌入且无原厂文本证据证明为当天发布的条目恢复为 NULL
UPDATE `source_items`
SET `published_at` = NULL
WHERE DATE(`published_at`) = '2026-09-27'
  AND `title` NOT LIKE '%Sep 27%'
  AND `title` NOT LIKE '%2026-09-27%'
  AND `title` NOT LIKE '%9月27%';
